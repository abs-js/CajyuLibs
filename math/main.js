export const CajyuLib = {
  soma: (a, b) => a + b,
  subtracao: (a, b) => a - b,
  multiplicacao: (a, b) => a * b,
  divisao: (a, b) => b !== 0 ? a / b : NaN,
  modulo: (a, b) => a % b,
  abs: Math.abs,
  floor: Math.floor,
  ceil: Math.ceil,
  round: Math.round,
  sqrt: Math.sqrt,
  pow: Math.pow,
  min: (...args) => Math.min(...args),
  max: (...args) => Math.max(...args),
  sin: Math.sin,
  cos: Math.cos,
  tan: Math.tan,
  asin: Math.asin,
  acos: Math.acos,
  atan: Math.atan,
  atan2: Math.atan2,
  PI: Math.PI,
  E: Math.E,
  random: () => Math.random(),
  randomInt: (min, max) => Math.floor(Math.random() * (max - min + 1)) + min,
  clamp: (n, min, max) => Math.min(Math.max(n, min), max),
  lerp: (a, b, t) => a + (b - a) * t
};
